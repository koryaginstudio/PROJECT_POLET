#!/bin/zsh
# Фазы 2 и 3 на коде 21 сентября, вечер. Копия `замеры-18-09/довод-фаз-2-3.sh`
# с тремя отличиями:
#
#   * пишет в `замеры-21-09/`, рядом с фазой 1 того же круга;
#   * предел — исправленной копией `замеры-21-09/потолок-зон.py`: прежний
#     скрипт не выключал приоритет распределения, вошедший в цель 21-го, и
#     «наш как MILP» решал бы не ту задачу, что точная модель;
#   * в пересчёте теперь действует оборудование (`Params.stock`), а в
#     разыгранном состоянии исполнитель, выехавший к визиту до момента
#     пересчёта, к нему и едет. Числа пересчёта, выбытия и прокола обязаны
#     сдвинуться — это находка, а не опечатка. Утренний план не менялся:
#     фаза 1 в силе (`база-против-нас-интервалы.txt` воспроизвёл её до
#     цифры).
#
# Бюджет здесь в СЕКУНДАХ: HiGHS меряется часом, пересчёт — полутора
# секундами. Запускать под caffeinate, с ОТКРЫТОЙ крышкой и на питании:
# clamshell-сон на батарее caffeinate не отменяет. Параллельной нагрузки не
# давать. Журнал сна снимается в конце — хоть одна запись Sleep, и
# результаты не замер.
#
# Имена переменных латиницей: zsh не берёт кириллицу в идентификаторах.
cd "$(dirname "$0")/.."
SRC="замеры-16-09"
OUT="замеры-21-09"
export PYTHONPATH=.

START=$(date '+%F %T')
echo "фазы 2–3 начаты: $START"
echo "питание: $(pmset -g batt | head -1)"
echo "отпечаток кода: $(python3 -c 'from vrptw.server import отпечаток_кода; print(отпечаток_кода())')"
echo "коммит: $(git rev-parse --short HEAD)"

run() {
  local name="$1"; shift
  echo "═══ $name   [$(date '+%T')]"
  if python3 -u "$@" > "$OUT/$name.txt" 2>&1; then
    echo "    готово $name [$(date '+%T')]"
  else
    echo "    УПАЛО $name [$(date '+%T')] — хвост:"
    tail -6 "$OUT/$name.txt" | sed 's/^/      /'
  fi
}

echo "───── фаза 2: HiGHS, один на свободной машине ─────"
run "потолок-час" "$OUT/потолок-зон.py" 3600

echo "───── фаза 3: бюджет в секундах, строго по одному ─────"
run "пересчёт-на-зонах"      "$SRC/пересчёт-на-зонах.py" replan
run "выбытие-на-зонах"       "$SRC/пересчёт-на-зонах.py" dropout
run "прокол-на-зонах"        "$SRC/на-зонах.py" прокол
run "равномерность-на-зонах" "$SRC/на-зонах.py" равномерность

echo "───── журнал сна за время прогона ─────"
SLEPT=$(pmset -g log | awk -v s="$START" '$1" "$2 >= s' | grep -cE " Sleep  ")
echo "записей Sleep с $START: $SLEPT"
if [ "$SLEPT" -gt 0 ]; then echo "МАШИНА СПАЛА — результаты фаз 2–3 не замер"; else echo "машина не спала — замеры действительны"; fi
echo "фазы 2–3 закончены: $(date '+%F %T')"
