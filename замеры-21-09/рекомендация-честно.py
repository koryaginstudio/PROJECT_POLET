"""Рекомендация без подгонки: отбор и оценка на разных зёрнах, смены — по зёрнам.

Зачем. В «дешёвой рекомендации» двое лучших выбраны замером «кого
переобучать» на зёрнах 0–7 и там же, на зёрнах 0–7, измерены. Это отбор
победителя: выигрыш завышен уже тем, что их выбрали как лучших ровно на
этих прогонах. Признак — после правки, почти не тронувшей головные числа
(приоритет распределения, `562fa71`), «двое лучших» сменились с E03+E04 на
E03+E07. И второе: расписание там подбирается ОДИН раз, зерном 0, а
интервал считается только по зёрнам оценки. Так в 19 сентября уже
попадались — «только смены вредят» и «197,8 из 205» держались на одном
зерне подбора.

Что здесь иначе.

  * ОТБОР — прежний: двое лучших берутся из `порядок.txt` круга 21-го,
    где они выбраны на зёрнах 0–7.
  * ОЦЕНКА — на зёрнах 8–15, которых отбор не видел: солвер с зерном s,
    симуляция с зерном 100 + s, то есть 108–115 против 100–107 у отбора.
  * СМЕНЫ — подбор на пяти зёрнах оптимизатора (0–4); его собственная
    симуляция берёт зёрна 0–4 и с оценкой не пересекается.
  * ИНТЕРВАЛ идёт по обоим источникам случайности. Для строк со сменами:
    полуширина = корень из суммы квадратов двух частей — t(4)·sd/√5 по
    средним пяти зёрен подбора и t(7)·sd/√8 по средним восьми зёрен
    оценки. Для строк без смен — t(7) по восьми зёрнам оценки. Везде t, а
    не 1,96: на пяти и восьми точках это на 20–40% шире, и прежние
    замеры интервал поэтому занижали.

Протокол оценки тот же, что в «дешёвой рекомендации»: 1500 шагов, 200
прогонов симуляции, переобучение — добавить навык подключения.

Запуск из корня (бюджет в шагах, сон не портит, но параллельную
нагрузку не давать):
    python3 замеры-21-09/рекомендация-честно.py > замеры-21-09/рекомендация-честно.txt
"""

import copy
import math
import multiprocessing as mp
import statistics as st
import subprocess
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from vrptw import shiftopt  # noqa: E402
from vrptw.core.load import load_day  # noqa: E402
from vrptw.core.simulate import monte_carlo  # noqa: E402
from vrptw.solvers import fast, improved  # noqa: E402

ЗОНЫ = ("восток", "юго-восток", "югоцентр")
ОЦЕНКА = list(range(8, 16))        # зёрна оценки — отбор шёл на 0–7
ЗЁРНА_ПОДБОРА = list(range(5))     # зёрна оптимизатора смен
ПАР = improved.Params(lns_seconds=0.0, lns_iterations=1500)
ВАРИАНТЫ = ("как есть", "2 лучших", "весь класс")
МЕТРИКИ = ("назначено", "выполнено", "инженеров", "км", "срывов")
T95 = {4: 2.776, 7: 2.365}

ПОРЯДОК = Path(__file__).with_name("порядок.txt").read_text().strip().split(",")
ЛУЧШИЕ = set(ПОРЯДОК[:2])


def обучить(d0, кому):
    d = copy.copy(d0)
    d.engineers = [copy.copy(e) for e in d0.engineers]
    for e in d.engineers:
        if e.id in кому:
            e.skills = set(e.skills) | {"install"}
    return d


def вариант(зона, имя):
    б = load_day(зона, quiet=True)
    if имя == "как есть":
        return б
    if имя == "2 лучших":
        return обучить(б, ЛУЧШИЕ)
    return обучить(б, {e.id for e in б.engineers if e.skills == {"local"}})


def замер(day, seed):
    p = fast.solve(day, params=ПАР, seed=seed)
    беды = p.check_invariants(day)
    assert not беды, беды[:2]
    mc = monte_carlo(day, p, runs=200, seed=100 + seed)
    m = p.metrics(day)
    return (m["assigned"], mc.done_mean, m["engineers_used"], m["km_total"],
            mc.reasons_mean.get("missed_window", 0.0))


def задача(арг):
    зона, имя, зерно = арг          # зерно None — без подбора смен
    d = вариант(зона, имя)
    профиль = None
    if зерно is not None:
        sp = shiftopt.optimize(d, restarts=12, seed=зерно, shift_len=None)
        starts, _ = shiftopt.refine(d, sp.starts, solver_seed=зерно, sim_seed=зерно,
                                    rounds=2, runs=120, lns_iterations=300,
                                    shift_len=None)
        d = shiftopt.apply(d, starts, shift_len=None)
        профиль = sorted(starts)
    return арг, [замер(d, s) for s in ОЦЕНКА], профиль


def ци_оценки(xs):
    """Среднее ± t(7)·sd/√n по зёрнам оценки."""
    m = st.mean(xs)
    return m, T95[len(xs) - 1] * st.stdev(xs) / math.sqrt(len(xs))


if __name__ == "__main__":
    коммит = subprocess.run(["git", "rev-parse", "--short", "HEAD"],
                            capture_output=True, text=True).stdout.strip()
    задачи = [(з, в, None) for з in ЗОНЫ for в in ВАРИАНТЫ] + \
             [(з, в, g) for з in ЗОНЫ for в in ВАРИАНТЫ for g in ЗЁРНА_ПОДБОРА]
    print("Рекомендация без подгонки: отбор на зёрнах 0–7, оценка на 8–15, "
          "смены на пяти зёрнах подбора")
    print(f"поверх {коммит}; двое лучших из порядка круга 21-го: "
          f"{'+'.join(sorted(ЛУЧШИЕ))} (порядок {','.join(ПОРЯДОК)})")
    print(f"задач: {len(задачи)}, параллельно по 4; старт {time.strftime('%F %T')}\n",
          flush=True)

    итог, профили = {}, {}
    with mp.Pool(4) as pool:
        for n, (арг, значения, профиль) in enumerate(pool.imap_unordered(задача, задачи), 1):
            итог[арг] = значения
            if профиль is not None:
                профили[арг] = профиль
            print(f"  [{n:2}/{len(задачи)}] {арг[0]:11} {арг[1]:11} "
                  f"{'без смен' if арг[2] is None else f'зерно подбора {арг[2]}'}",
                  flush=True)

    def по_зонам(имя, зерно, k):
        """Сумма по трём зонам — по каждому зерну оценки."""
        return [sum(итог[(з, имя, зерно)][i][k] for з in ЗОНЫ)
                for i in range(len(ОЦЕНКА))]

    база = {k: по_зонам("как есть", None, k) for k in range(len(МЕТРИКИ))}
    print()
    print(f"«как есть» на зёрнах оценки 8–15: назначено {st.mean(база[0]):.1f}, "
          f"выполнено {st.mean(база[1]):.1f}, инженеров {st.mean(база[2]):.2f}, "
          f"км {st.mean(база[3]):.0f}")
    print("(для сверки: на зёрнах 0–7 круг 21-го давал 191,5 / 168,9 / 38,75 / 1224)")
    print()
    print("═" * 100)
    print("разница к «как есть», три участка вместе, 95%, по всем источникам случайности")
    print("═" * 100)

    сводка = []
    for имя in ВАРИАНТЫ:
        for со_сменами in (False, True):
            if имя == "как есть" and not со_сменами:
                continue
            ярлык = ("только смены" if имя == "как есть" else
                     f"{имя} + смены" if со_сменами else имя)
            if имя == "2 лучших":
                ярлык = ярлык.replace("2 лучших", f"2 лучших ({'+'.join(sorted(ЛУЧШИЕ))})")
            куски, в_плюс = [], None
            for k, метрика in enumerate(МЕТРИКИ[:4]):
                if not со_сменами:
                    разн = [a - b for a, b in zip(по_зонам(имя, None, k), база[k])]
                    m, h = ци_оценки(разн)
                else:
                    # d[g][i] — разница на зерне подбора g и зерне оценки i
                    d = [[a - b for a, b in zip(по_зонам(имя, g, k), база[k])]
                         for g in ЗЁРНА_ПОДБОРА]
                    по_подбору = [st.mean(ряд) for ряд in d]
                    по_оценке = [st.mean(d[g][i] for g in range(len(ЗЁРНА_ПОДБОРА)))
                                 for i in range(len(ОЦЕНКА))]
                    m = st.mean(по_подбору)
                    h_подбор = T95[len(по_подбору) - 1] * st.stdev(по_подбору) / math.sqrt(len(по_подбору))
                    h_оценка = T95[len(по_оценке) - 1] * st.stdev(по_оценке) / math.sqrt(len(по_оценке))
                    h = math.hypot(h_подбор, h_оценка)
                    if метрика == "выполнено":
                        в_плюс = (sum(1 for x in по_подбору if x > 0), len(по_подбору),
                                  min(по_подбору), max(по_подбору))
                ноль = " (ноль внутри)" if abs(m) <= h else ""
                ф = ".0f" if метрика == "км" else ".1f"
                куски.append(f"{метрика} {m:+{ф}} ± {h:{ф}}{ноль}")
            print(f"  {ярлык}")
            print("      " + ",  ".join(куски))
            if в_плюс:
                print(f"      по зёрнам подбора выполнено {в_плюс[2]:+.1f} … {в_плюс[3]:+.1f}, "
                      f"в плюс {в_плюс[0]} из {в_плюс[1]}")
            сводка.append(ярлык)
    print()
    print("═" * 100)
    print("подобранные часы выхода (по зонам и зёрнам) — насколько разные расписания:")
    for з in ЗОНЫ:
        for имя in ВАРИАНТЫ:
            for g in ЗЁРНА_ПОДБОРА:
                print(f"  {з:11} {имя:11} зерно {g}: {профили[(з, имя, g)]}")
    print()
    print(f"конец: {time.strftime('%F %T')}")
