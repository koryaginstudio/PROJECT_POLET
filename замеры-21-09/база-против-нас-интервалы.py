"""Головная таблица с интервалами: наш план против базового варианта ТЗ.

`замеры-16-09/база-против-нас.py` печатает средние по восьми зёрнам без
интервала, а функциональные требования обещают постановщику, что все
числа раздела 4 сняты «с доверительными интервалами». Здесь то же самое,
теми же зёрнами и тем же бюджетом, плюс парный интервал.

Источники случайности два: зерно солвера и зерно симуляции. Базовый
вариант детерминирован, но его «выполнено» тоже разыгрывается, поэтому
пара — одно зерно: наш план на зерне s и базовый, оба сыгранные симуляцией
с зерном 100 + s. Интервал по восьми парам, по t с семью степенями
свободы, а не по 1,96.

Три участка складываются внутри зерна, и интервал считается по суммам:
так он отвечает на вопрос «что на трёх участках вместе», а не на
«что на каждом».

Первые четыре строки обязаны совпасть с `база-против-нас.txt` круга
21 сентября: утренний план с тех пор не менялся (оборудование и статусы
живут в пересчёте). Не совпали — это находка, а не опечатка.
"""
import statistics as st

from vrptw.core.domain import require_valid
from vrptw.core.load import load_day
from vrptw.core.simulate import monte_carlo
from vrptw.solvers import fast, improved, sequential

ЗОНЫ = ('восток', 'юго-восток', 'югоцентр')
СИДЫ = list(range(8))
ПАР = improved.Params(lns_seconds=0.0, lns_iterations=1500)
T_7 = 2.365          # t(0,975; 7)


def интервал(xs):
    m = st.mean(xs)
    return m, T_7 * st.stdev(xs) / len(xs) ** 0.5


по_зерну = {s: {"наш": [0, 0.0, 0, 0.0], "база": [0, 0.0, 0, 0.0]} for s in СИДЫ}
по_зоне = {}
for з in ЗОНЫ:
    d = load_day(з, quiet=True)
    база = require_valid(sequential.solve(d), d)
    mb = база.metrics(d)
    строки = []
    for s in СИДЫ:
        наш = require_valid(fast.solve(d, params=ПАР, seed=s), d)
        m = наш.metrics(d)
        вып_наш = monte_carlo(d, наш, runs=200, seed=100 + s).done_mean
        вып_база = monte_carlo(d, база, runs=200, seed=100 + s).done_mean
        for имя, мм, вып in (("наш", m, вып_наш), ("база", mb, вып_база)):
            t = по_зерну[s][имя]
            t[0] += мм["assigned"]; t[1] += вып
            t[2] += мм["engineers_used"]; t[3] += мм["km_total"]
        строки.append((m["assigned"], вып_наш, m["engineers_used"], m["km_total"],
                       mb["assigned"], вып_база, mb["engineers_used"], mb["km_total"]))
    по_зоне[з] = строки

print(f"{'зона':13}{'план':7}{'назнач':>8}{'выполн':>8}{'инж':>6}{'км':>8}"
      f"{'км/назн':>9}")
print("─" * 60)
for з, строки in по_зоне.items():
    for имя, off in (("наш", 0), ("база", 4)):
        a = st.mean(r[off] for r in строки); v = st.mean(r[off + 1] for r in строки)
        e = st.mean(r[off + 2] for r in строки); k = st.mean(r[off + 3] for r in строки)
        print(f"{з if имя == 'наш' else '':13}{имя:7}{a:>8.1f}{v:>8.1f}{e:>6.1f}"
              f"{k:>8.0f}{k / a:>9.2f}")

print("\nТри участка вместе, по зерну: наш − база, среднее ± полуширина 95%, t(7)")
print("─" * 60)
for i, что in enumerate(("назначено", "выполнено", "исполнителей", "км валом")):
    наш = [по_зерну[s]["наш"][i] for s in СИДЫ]
    раз = [по_зерну[s]["наш"][i] - по_зерну[s]["база"][i] for s in СИДЫ]
    m, h = интервал(наш); dm, dh = интервал(раз)
    print(f"{что:14} наш {m:8.1f} ± {h:5.1f}   разность {dm:+8.1f} ± {dh:5.1f}   "
          f"по зёрнам {min(наш):.1f}…{max(наш):.1f}")

км_наш = [по_зерну[s]["наш"][3] / по_зерну[s]["наш"][0] for s in СИДЫ]
км_база = [по_зерну[s]["база"][3] / по_зерну[s]["база"][0] for s in СИДЫ]
отн = [a / b - 1 for a, b in zip(км_наш, км_база)]
m, h = интервал(км_наш); om, oh = интервал(отн)
print(f"{'км/назн.':14} наш {m:8.2f} ± {h:5.2f}   база {st.mean(км_база):.2f}   "
      f"разница {om:+.1%} ± {oh:.1%}")

# По участкам: км на назначенный визит — там, где базовому не выигрываем.
print("\nкм на назначенный визит по участкам, наш − база, по зёрнам")
for з, строки in по_зоне.items():
    раз = [r[3] / r[0] - r[7] / r[4] for r in строки]
    m, h = интервал(раз)
    print(f"  {з:12} {m:+.2f} ± {h:.2f}"
          f"{'   ноль внутри' if abs(m) <= h else ''}")
