#!/bin/zsh
# Фаза 1 перегенерации на коде 21 сентября. Только бюджет в ШАГАХ.
#
# Копия `замеры-20-09/фаза-1.sh` с тремя отличиями:
#
#   * пишет в `замеры-21-09/`, а не поверх круга 20-го;
#   * двое лучших для «дешёвой рекомендации» берутся из свежего порядка
#     кандидатов, а не вписаны руками. В прошлом скрипте стояло "E03,E04"
#     — это был верх порядка 20-го. Цель с тех пор изменилась, порядок
#     может стать другим, и тогда файл молча назвал бы «лучшими» не тех;
#   * в конце — `буфер-и-баланс`: он цитируется в CLAUDE.md и тоже
#     считается в шагах.
#
# Что изменилось в коде с прогона 20-го и чего ждать:
#
#   * ПРИОРИТЕТ РАСПРЕДЕЛЕНИЯ вошёл в цель (`562fa71`): несделанное
#     взвешено по ступени, авария → подключение → ремонт и дозаказ.
#     Меняется то, что считается планом, — ОБЯЗАНЫ измениться все файлы.
#     Парный замер (`приоритет.txt`) обещает: назначенное, выполненное и
#     число людей — в пределах шума; аварий без исполнителя — ноль;
#     подключений без исполнителя — примерно на два больше. Если головной
#     файл покажет иное — это находка, а не опечатка.
#   * Всё остальное за 20–21 сентября к солверу инертно: вывод selfcheck
#     совпадал построчно до этой правки.
#
# Бюджет в шагах: сон приостановит, но не испортит. Батарея допустима.
# Параллельная нагрузка — нет: скрипт сам гонит по два, третьего не надо.
#
# Имена переменных латиницей: zsh не берёт кириллицу в идентификаторах.
cd "$(dirname "$0")/.."
SRC="замеры-16-09"
OUT="замеры-21-09"
export PYTHONPATH=.

START=$(date '+%F %T')
echo "фаза 1 начата: $START"
echo "питание: $(pmset -g batt | tail -1 | sed 's/^[[:space:]]*//')"
echo "отпечаток кода: $(python3 -c 'from vrptw.server import отпечаток_кода; print(отпечаток_кода())')"
echo "коммит: $(git rev-parse --short HEAD)"

run() {
  local name="$1"; shift
  echo "═══ $name   [$(date '+%T')]"
  if python3 -u "$@" > "$OUT/$name.txt" 2>&1; then
    echo "    готово $name [$(date '+%T')]"
  else
    echo "    УПАЛО $name [$(date '+%T')] — хвост:"
    tail -6 "$OUT/$name.txt" | sed 's/^/      /'
  fi
}

echo "───── бюджет в шагах, по два ─────"
run "база-против-нас"  "$SRC/база-против-нас.py" &
run "кого-переобучать" "$SRC/кого-переобучать.py" &
wait

ORDER=$(python3 "$SRC/порядок.py" "$OUT/кого-переобучать.txt")
echo "$ORDER" > "$OUT/порядок.txt"
echo "порядок кандидатов: $ORDER"
TOP2=$(echo "$ORDER" | cut -d, -f1-2)
echo "двое лучших: $TOP2"

run "кривая-переобучения"   "$SRC/кривая-переобучения.py" "$ORDER" &
run "обучить-против-нанять" "$SRC/обучить-против-нанять.py" &
wait
run "разрыв-смены" "$SRC/разрыв-смены.py" &
run "перенос-окон" "$SRC/перенос-окон.py" &
wait
run "дефицит-после" "$SRC/дефицит-после.py" "$ORDER" &
run "кто-не-влез"   "$SRC/кто-не-влез.py" &
wait
run "физпредел-зон" "$SRC/физпредел-зон.py" &
run "окна-спрос"    "$SRC/окна-спрос.py" &
wait
run "обязательства-на-зонах"     "$SRC/на-зонах.py" обязательства &
run "равномерность-против-людей" "$SRC/равномерность-против-людей.py" &
wait
run "дешёвая-рекомендация" "$SRC/дешёвая-рекомендация.py" "$TOP2" &
run "буфер-и-баланс"       "замеры-20-09/буфер-и-баланс.py" &
wait

echo "───── сон за время фазы (для протокола; на шаги не влияет) ─────"
SLEPT=$(pmset -g log | awk -v s="$START" '$1" "$2 >= s' | grep -cE " Sleep  ")
echo "записей Sleep с $START: $SLEPT"
echo "фаза 1 закончена: $(date '+%F %T')"
