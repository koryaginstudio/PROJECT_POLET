"""Сколько ещё людей нужно, чтобы закрыть остаток.

Постановщик на сессии вопросов продиктовал формат дословно: «желательно
уместить все или сказать, что для того чтобы выполнить оставшиеся заявки,
нужно ещё плюс 5 исполнителей». И рядом: слоты «можно открывать
дополнительно по решению диспетчера». Ответ поэтому — не прикидка, а
действие: сколько слотов открыть и каких.

Считается солвером, а не арифметикой. «Часы работы делить на длину
смены» здесь врёт в обе стороны: не знает географии, окон и того, что
утренний пик и вечерний хвост одним человеком не закрыть. Поэтому к дню
по одному добавляются инженеры и день пересчитывается, пока остаток не
закроется или пока добавление перестанет помогать.

ДОБАВЛЯЮТСЯ НЕ ПРИДУМАННЫЕ ЛЮДИ, а ещё один слот из профилей самой
бригады — те же навыки, транспорт и часы смены, что у настоящих
инженеров. Первая версия заводила специалиста ровно под навык и окно
заявки и выдавала смены «20:00–22:00» — двухчасовой слот не откроет
никто, а ответ выходил «по человеку на заявку», то есть пересчётом
остатка, а не ответом.

Выбор слота на каждом шаге: из профилей, способных взять хоть что-то из
остатка, первым пробуется тот, что покрывает больше заявок, потом —
шире по навыкам, потом с машиной. Не помог — пробуется следующий.
Останавливаемся, только когда не помог ни один: тогда оставшееся
неустранимо добавлением людей, и это называется отдельно, а не
прячется в раздутое число.

ЗЁРНА. Солвер бросает кости, и ответ на одном зерне — это не ответ: на
востоке одно зерно из трёх закрывает остаток двумя слотами и оставляет
одну заявку, два других — тремя слотами целиком. Интервал обязан идти по
всем источникам случайности, поэтому считается на нескольких зёрнах.

В голову ответа идёт НАИБОЛЬШЕЕ число слотов среди прогонов, закрывших
остаток, а не наименьшее. Наименьшее было бы «лучшим зерном, выданным за
вывод» — ровно та ловушка, на которой проект уже дважды попадался
(«197,8 из 205» держалось на одном зерне). Диспетчер получит план одним
прогоном, и ему нужно число, которое закрывает остаток надёжно, а не
при удачных костях. Разброс отдаётся рядом, и если какой-то прогон
остаток не закрыл, это сказано отдельно.

Бюджет поиска — в шагах, а не в секундах: так ответ воспроизводится у
любого, кто скачал репозиторий, и не зависит от того, чем занята
машина. Пятьсот шагов — за плато (~200), которое мерили отдельно.
"""

from __future__ import annotations

import copy
from collections import Counter

from .core.domain import SKILL_TITLES, TRANSPORT, Day, Engineer, Order
from .core.load import БРИГАДЫ
from .solvers import fast, improved

ШАГОВ = 500          # бюджет поиска на один пересчёт, за плато
ЗЁРНА = (0, 1, 2)    # сколько раз бросать кости
ПРЕДЕЛ = 20          # больше слотов не открывают: это уже не остаток, а другой штат


def _профили() -> list[tuple[frozenset, str, int, int]]:
    """Различимые профили бригады: навыки, транспорт, начало и конец смены."""
    видел: set = set()
    out = []
    for навыки, транспорт, начало, конец in БРИГАДЫ:
        ключ = (frozenset(навыки), транспорт, начало, конец)
        if ключ not in видел:
            видел.add(ключ)
            out.append(ключ)
    return out


def _годится(профиль, заявка: Order) -> bool:
    навыки, транспорт, начало, конец = профиль
    if заявка.skill not in навыки:
        return False
    if заявка.requires_transport and заявка.requires_transport != транспорт:
        return False
    # Смена обязана пересекаться с окном — иначе слот бесполезен для
    # этой заявки при любом маршруте.
    return начало < заявка.window_end and конец > заявка.window_start


def _кандидаты(остаток: list[Order]) -> list:
    """Профили, способные взять хоть что-то из остатка, — лучшие первыми."""
    оценка = []
    for п in _профили():
        сколько = sum(1 for o in остаток if _годится(п, o))
        if сколько:
            навыки, транспорт, _, _ = п
            оценка.append(((сколько, len(навыки), транспорт == "car"), п))
    оценка.sort(key=lambda x: x[0], reverse=True)
    return [п for _, п in оценка]


def _слот(день: Day, профиль, номер: int) -> Engineer:
    """Ещё один инженер по профилю бригады, из офиса участка.

    Офис берётся у городского инженера: у выездных дом в своём дальнем
    городе, и сажать туда дополнительный слот значило бы решать за
    диспетчера, где ему нужны люди.
    """
    навыки, транспорт, начало, конец = профиль
    офисные = [e for e in день.engineers if not e.id.startswith("X")]
    образец = Counter((e.home_lat, e.home_lon) for e in офисные).most_common(1)[0][0]
    дом = next(e for e in офисные if (e.home_lat, e.home_lon) == образец)
    return Engineer(
        id=f"X{номер:02d}", name=f"Дополнительный слот {номер + 1}",
        skills=set(навыки), grade=2,
        home_node=дом.home_node, home_lat=дом.home_lat, home_lon=дом.home_lon,
        home_address=дом.home_address,
        shift_start=начало, shift_end=min(конец, день.hard_end),
        speed=1.0, transport=транспорт)


def _решить(день: Day, база: improved.Params, зерно: int):
    параметры = copy.copy(база)
    параметры.lns_seconds = 0.0
    параметры.lns_iterations = ШАГОВ
    план = fast.solve(день, params=параметры, seed=зерно)
    проблемы = план.check_invariants(день)
    if проблемы:
        raise RuntimeError(f"план с дополнительными слотами невалиден: {проблемы[:2]}")
    return план


def _на_зерне(день: Day, база: improved.Params, зерно: int) -> dict:
    d = copy.copy(день)
    d.engineers = list(день.engineers)
    план = _решить(d, база, зерно)
    было = len(план.unassigned)
    открыто: list = []

    while план.unassigned and len(открыто) < ПРЕДЕЛ:
        помогло = False
        for п in _кандидаты(план.unassigned):
            d.engineers = d.engineers + [_слот(d, п, len(открыто))]
            следующий = _решить(d, база, зерно)
            if следующий.assigned_count > план.assigned_count:
                открыто.append(п)
                план = следующий
                помогло = True
                break
            d.engineers = d.engineers[:-1]
        if not помогло:
            break

    return {"зерно": зерно, "было": было, "открыто": открыто,
            "не_закрыть": план.unassigned, "день": d}


def _подпись(профиль) -> dict:
    навыки, транспорт, начало, конец = профиль
    return {
        "skills": sorted(навыки),
        "skills_title": ", ".join(SKILL_TITLES.get(s, s) for s in sorted(навыки)),
        "transport": транспорт,
        "transport_title": TRANSPORT[транспорт]["title"],
        "shift_start": начало,
        "shift_end": конец,
    }


def _людей(n: int) -> str:
    """«исполнитель» в нужном падеже: 1 исполнитель, 2 исполнителя, 5 исполнителей."""
    if n % 10 == 1 and n % 100 != 11:
        return "исполнитель"
    if n % 10 in (2, 3, 4) and n % 100 not in (12, 13, 14):
        return "исполнителя"
    return "исполнителей"


def _заявок(n: int) -> str:
    if n % 10 == 1 and n % 100 != 11:
        return "заявку"
    if n % 10 in (2, 3, 4) and n % 100 not in (12, 13, 14):
        return "заявки"
    return "заявок"


def _hhmm(m: int) -> str:
    return f"{m // 60:02d}:{m % 60:02d}"


def выбрать_голову(прогоны: list[dict]) -> dict:
    """Какой прогон идёт в голову ответа.

    Среди закрывших остаток — тот, что закрыл его НАИБОЛЬШИМ числом
    слотов: надёжное число, а не удачное. Если не закрыл ни один — тот,
    что оставил меньше всего, при равенстве меньшим числом слотов.

    Вынесено отдельно ради проверки. На нынешних данных прогоны, закрывшие
    остаток, всегда совпадают по числу слотов — на востоке оба по +3, на
    юго-востоке оба по +4, — и «наибольшее» с «наименьшим» там одно
    число. Сторож на живых данных этот выбор поэтому не видит вовсе:
    замена `max` на `min` проходила бы зелёной. Правило проверяется на
    прогонах, которые расходятся, — в selfcheck.
    """
    закрывшие = [p for p in прогоны if not p["не_закрыть"]]
    if закрывшие:
        return max(закрывшие, key=lambda p: len(p["открыто"]))
    return min(прогоны, key=lambda p: (len(p["не_закрыть"]), len(p["открыто"])))


def описать_надёжность(прогоны: list[dict]) -> str:
    """Одна фраза о том, насколько прогоны согласны между собой.

    «Одно и то же» говорится, только если числа правда совпали. Прежде
    фраза срабатывала всякий раз, когда все прогоны закрыли остаток, и на
    юго-востоке при +4, +5 и +3 печатала «одно и то же на всех трёх».
    """
    закрывшие = [p for p in прогоны if not p["не_закрыть"]]
    не_закрыли = len(прогоны) - len(закрывшие)
    разброс = sorted({len(p["открыто"]) for p in закрывшие})
    if не_закрыли and закрывшие:
        return (f"На {не_закрыли} прогоне из {len(прогоны)} остаток не "
                f"закрылся целиком — число взято по прогонам, где закрылся.")
    if not закрывшие:
        return f"Остаток не закрылся ни на одном из {len(прогоны)} прогонов."
    if len(разброс) > 1:
        return (f"На разных прогонах от +{разброс[0]} до +{разброс[-1]}; "
                f"взято наибольшее — оно закрывает остаток надёжно.")
    return f"Одно и то же на всех {len(прогоны)} прогонах."


def сколько_нужно(день: Day, база: improved.Params,
                  зёрна=ЗЁРНА) -> dict:
    """Сколько слотов открыть, чтобы закрыть остаток дня, и каких.

    В голову ответа идёт прогон, закрывший остаток НАИБОЛЬШИМ числом
    слотов — надёжное число, а не удачное; см. модуль. Если остаток не
    закрыл ни один прогон — тот, что закрыл больше всего. Разброс по
    зёрнам отдаётся рядом.
    """
    прогоны = [_на_зерне(день, база, з) for з in зёрна]
    голова = выбрать_голову(прогоны)
    закрывшие = [p for p in прогоны if not p["не_закрыть"]]
    не_закрыли = len(прогоны) - len(закрывшие)

    по_профилю = Counter(голова["открыто"])
    слоты = [{**_подпись(п), "count": n}
             for п, n in sorted(по_профилю.items(),
                                key=lambda kv: (-kv[1], kv[0][2]))]

    нужно = len(голова["открыто"])
    было = голова["было"]
    остаётся = голова["не_закрыть"]

    # Фраза — в том виде, в каком её продиктовал постановщик.
    if было == 0:
        фраза = "Все заявки распределены, дополнительные исполнители не нужны."
    elif not остаётся:
        фраза = (f"Чтобы выполнить оставшиеся {было} {_заявок(было)}, "
                 f"нужно ещё +{нужно} {_людей(нужно)}.")
    else:
        закрыто = было - len(остаётся)
        фраза = (f"Из оставшихся {было} {_заявок(было)} ещё +{нужно} "
                 f"{_людей(нужно)} закроют {закрыто}; "
                 f"{len(остаётся)} не закрыть добавлением людей.")

    # Надёжность — отдельной фразой, а не внутри продиктованной: ту
    # постановщик назвал дословно, и портить её оговорками незачем.
    надёжность = описать_надёжность(прогоны) if было else ""

    return {
        "kind": "staffing",
        "unassigned_now": было,
        "needed": нужно,
        "closes_all": not остаётся,
        "reliability": надёжность,
        "phrase": фраза,
        "slots": слоты,
        # То, что не закрывается даже дополнительными людьми: окно уже не
        # достать из офиса, или работу не берёт ни один профиль бригады.
        # Называется отдельно, чтобы не прятать это в раздутое число.
        "still_unassigned": [o.id for o in остаётся],
        "seeds": [{"seed": p["зерно"], "needed": len(p["открыто"]),
                   "left": len(p["не_закрыть"])} for p in прогоны],
        "method": (f"к дню по одному добавляются слоты из профилей бригады, "
                   f"день пересчитывается солвером ({ШАГОВ} шагов), "
                   f"{len(зёрна)} зерна; в голове — меньшее число слотов, "
                   f"закрывшее остаток"),
    }
