"""Где движок держит рабочее состояние: архив расчётов, сохранённые
сравнения, журнал дня и настройки компании.

Каталог задаётся в одном месте, потому что состояние надо уметь уводить
в сторону. Прежде `server check` заводил `Stand()` в текущем каталоге и
работал по боевым файлам: дописывал три записи в архив и звал
`journal/reset` по дню 1 и по зоне «восток» — то есть стирал всё, что
ввёл диспетчер. Проверка, которая портит проверяемое, хуже отсутствия
проверки: она делает это молча и ровно тогда, когда её просят прогнать
первой, — а обе записки передачи велят начинать именно с неё.

Кэш планов сюда не входит намеренно. Он не состояние, а сбережённый
счёт: ключ включает отпечатки настроек и кода, чужого не отдаст, а
расчёт зоны стоит около восьмидесяти секунд — уводить его в сторону
значило бы платить эти секунды на каждой проверке.

Путь читается при каждом обращении, а не при загрузке модуля: `check`
переводит его на временный каталог уже после того, как всё
импортировано.
"""

import os
from pathlib import Path

_выбранный: Path | None = None


def state_dir() -> Path:
    """Каталог состояния. По умолчанию — текущий, как было всегда."""
    if _выбранный is not None:
        return _выбранный
    из_среды = os.environ.get("VRPTW_STATE_DIR")
    return Path(из_среды) if из_среды else Path(".")


def use_state_dir(path) -> None:
    """Увести состояние в сторону. Зовётся до создания `Stand`."""
    global _выбранный
    _выбранный = Path(path)
    _выбранный.mkdir(parents=True, exist_ok=True)


def runs_path() -> Path:
    return state_dir() / ".vrptw-runs.json"


def compares_path() -> Path:
    return state_dir() / ".vrptw-compares.json"


def journal_dir() -> Path:
    return state_dir() / ".vrptw-journal"


def replans_dir() -> Path:
    """Планы сохранённых пересчётов — ровно те, что видели на экране."""
    return state_dir() / ".vrptw-replans"


def settings_file() -> Path:
    return state_dir() / ".vrptw-settings.json"


# ─── запись списков: архив расчётов и сохранённые сравнения ───
#
# Оба файла — json-список, и оба правятся сразу несколькими: диспетчер
# через браузер, замер из терминала, проверка. Прежде каждый писал файл
# целиком из своей памяти, и запись одного бесследно исчезала под
# записью другого. Поэтому здесь read-modify-write целиком под
# межпроцессной блокировкой: список читается с диска прямо перед
# правкой, а не берётся из того, что процесс загрузил при старте.
#
# Пишем во временный файл рядом и подменяем `os.replace`: обрыв на
# полпути не должен оставить обрезанный архив. Переименование в пределах
# одного каталога атомарно.

import json
import tempfile
from contextlib import contextmanager

from .compat import запереть, отпереть


@contextmanager
def _замок(path: Path):
    """Межпроцессная блокировка на отдельном файле-замке.

    Не на самом архиве: его подменяют `os.replace`, и блокировка,
    взятая на старом inode, новый уже не защищает. `fcntl` есть не везде —
    на Windows замок берёт `msvcrt` (compat.py).
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    файл = path.with_name(path.name + ".lock")
    with open(файл, "wb") as f:
        запереть(f)
        try:
            yield
        finally:
            отпереть(f)


def прочитать_список(path: Path) -> list:
    """Список с диска. Битый файл — не повод не открыться."""
    if not path.exists():
        return []
    try:
        прочитанное = json.loads(path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return []
    return прочитанное if isinstance(прочитанное, list) else []


def _записать_список(path: Path, данные: list) -> None:
    fd, врем = tempfile.mkstemp(dir=str(path.parent),
                               prefix=path.name + ".", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            json.dump(данные, f, ensure_ascii=False)
            f.flush()
            os.fsync(f.fileno())
        os.replace(врем, path)
    except BaseException:
        Path(врем).unlink(missing_ok=True)
        raise


def изменить_список(path: Path, действие):
    """Прочитать список с диска, дать его изменить и записать обратно.

    `действие` получает список, каким он лежит на диске **сейчас**, и
    правит его на месте; что оно вернёт — вернётся звавшему. Всё вместе
    идёт под блокировкой, поэтому чужая запись не потеряется.

    Возвращает пару: список после правки и то, что вернуло `действие`.
    """
    with _замок(path):
        текущие = прочитать_список(path)
        итог = действие(текущие)
        _записать_список(path, текущие)
        return текущие, итог
