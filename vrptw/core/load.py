# точку в соответствующем городе; такую точку предлагается считать домом
# исполнителя». Пятьдесят километров — это примерно граница, за которой
# ежедневная маятниковая поездка перестаёт быть правдоподобной.
ДАЛЬНИЙ_КМ = 50.0

# Сколько заявок должно набраться, чтобы держать там своего человека.
# Одна-две заявки в отдалении — это не основание для постоянной точки,
# их честнее оставить городским с длинным перегоном.
КЛАСТЕР_МИН = 3


def _дальние_кластеры(orders, office: dict) -> list[dict]:
    """Группы заявок далеко от офиса, каждой — своя стартовая точка.

    Кластеры ищутся по данным, а не по списку городов: список пришлось бы
    пополнять руками при каждой новой выгрузке, и он молча устаревал бы.
    Правило простое — заявки дальше `ДАЛЬНИЙ_КМ` от офиса склеиваются в
    группы по взаимной близости; точкой старта становится их центр.
    """
    далёкие = [o for o in orders
               if _км(o.lat, o.lon, office["lat"], office["lon"]) > ДАЛЬНИЙ_КМ]

    # Простая склейка по близости к центру уже набранной группы. Порядок
    # обхода фиксирован сортировкой, поэтому результат воспроизводится.
    кластеры: list[list] = []
    for o in sorted(далёкие, key=lambda o: (o.lat, o.lon, o.id)):
        for к in кластеры:
            ц_lat = sum(x.lat for x in к) / len(к)
            ц_lon = sum(x.lon for x in к) / len(к)
            if _км(o.lat, o.lon, ц_lat, ц_lon) <= ДАЛЬНИЙ_КМ / 2:
                к.append(o)
                break
        else:
            кластеры.append([o])

    out = []
    for к in sorted(кластеры, key=len, reverse=True):
        if len(к) < КЛАСТЕР_МИН:
            continue
        out.append({
            "lat": sum(o.lat for o in к) / len(к),
            "lon": sum(o.lon for o in к) / len(к),
            "orders": к,
            "skills": {o.skill for o in к},
            "minutes": sum(o.est_minutes for o in к),
            "address": (к[0].address or "").split(",")[0] or "выездная точка",
        })
    return out


def _км(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    """Расстояние по прямой, километры. Для отбора кластеров этого хватает."""
    dx = (lat1 - lat2) * 111.0
    dy = (lon1 - lon2) * 111.0 * math.cos(math.radians((lat1 + lat2) / 2))
    return (dx * dx + dy * dy) ** 0.5


def build_engineers(n: int, office: dict, orders=None) -> list[Engineer]:
    """Инженеры зоны: выезжают из офиса, смены веером до 22:00.

    Если в дне есть заявки в дальних городах, часть людей базируется
    там. Сколько именно — по объёму работы: часы у клиента плюс запас на
    разъезды внутри города, делённые на длину смены. Навыки такому
    человеку даются те, которые в его городе нужны, иначе он не сможет
    взять ничего.
    """
    out: list[Engineer] = []
    дальние = _дальние_кластеры(orders, office) if orders else []

    # Раздаём сначала выездных, потом городских: так у выездного всегда
    # есть нужный навык, а городские добирают остаток веера.
    места: list[tuple[dict | None, set[str] | None]] = []
    for к in дальние:
        # По одному на кластер — это замерено, а не прикинуто.
        #
        # Первая версия считала людей по объёму работ (21,4 часа в Кашире
        # и Ступине делить на смену — трое), и это оказался худший из
        # полезных вариантов. Юго-восток, 6 зёрен, парно к «все из офиса»:
        #
        #   в городе  назначено  инженеров   км   разница назначено / км
        #        1       73,3      13,5     693   +0,3 ± 0,4  / −140 ± 100
        #        2       72,7      13,3     660   −0,3 ± 0,4  / −174 ±  69
        #        3       72,2      14,0     734   −0,8 ± 0,3  /  −99 ±  55
        #        4       72,0      13,0     831   −1,0 ± 0,5  /   −3 ±  79
        #
        # Один человек выигрывает по обеим метрикам ТЗ сразу: назначено не
        # падает, задействовано меньше людей, пробег меньше на 140 км.
        # Двое эквивалентны в пределах шума. Трое и больше уже отнимают
        # назначенные — запертая в дальнем городе ёмкость не помогает
        # городу, где тесно. Оставшиеся заявки дальнего города спокойно
        # берут городские: один базированный работает плацдармом, а не
        # закрывает город целиком.
        места.append((к, к["skills"]))
    места += [(None, None)] * max(0, n - len(места))

    for i, (кластер, навыки) in enumerate(места[:n]):
        skills, transport, start, end = БРИГАДЫ[i % len(БРИГАДЫ)]
        дом = кластер or office
        out.append(Engineer(
            id=f"E{i:02d}",
            name=ИМЕНА[i % len(ИМЕНА)],
            # Выездному нужны все навыки его города: он там один или почти
            # один, и подстраховать его некому.
            skills=set(навыки) if навыки else set(skills),
            grade=2,
            home_node=-1,
            home_lat=дом["lat"],
            home_lon=дом["lon"],
            home_address=дом.get("address"),
            shift_start=start,
            shift_end=end,
            speed=1.0,
            # В дальнем городе без машины делать нечего: расстояния там
            # больше городских, а общественный транспорт реже.
            transport="car" if кластер else transport,
        ))
    return out


def load_day(region: str, n_engineers: int = 14, date: str = "2026-08-17",
             quiet: bool = False) -> Day:
    """
    Собрать `Day` по зоне обслуживания.

    Сеть строится под координаты именно этого дня — приклеивать настоящий
    дом к ближайшему из наших шестисот синтетических означало бы ошибаться
    на километр в каждом перегоне и в обеих обязательных метриках.
    """
    from . import geocode
    from .osm import network_for_points

    region = region.lower().strip()
    if region not in REGIONS:
        raise ValueError(f"зона «{region}» неизвестна; есть: "
                         f"{', '.join(REGIONS)}")

    rows, office_text = read_orders_csv(REGIONS[region])
    if not office_text:
        raise ValueError(f"в файле зоны «{region}» нет адреса офиса — "
                         f"без стартовой точки план строить нельзя")

    texts = [r["address"] for r in rows if r["address"]] + [office_text]
    geo = geocode.geocode_all(texts, quiet=quiet)
    if not quiet:
        print(f"  адреса: {geocode.report(geo)}")

    # Кэш сети кладём в отдельный каталог, а не рядом с прочими
    # матрицами: общий шаблон `.gitignore` исключает матрицы под
    # «чужие наборы точек», а зоны заказчика — не чужой набор, это и
    # есть данные демонстрации. Без них на защите понадобился бы
    # интернет, а обещано обратное.
    return собрать_день(
        rows, office_text, geo, n_engineers=n_engineers, date=date,
        ident=region, quiet=quiet,
        сеть=lambda points: network_for_points(points, quiet=quiet,
                                               cache_dir=DATA_DIR / "сети"))


def собрать_день(rows: list[dict], office_text: str, geo: dict, *,
                 n_engineers: int, date: str, ident: str, сеть,
                 quiet: bool = False) -> Day:
    """
    `Day` из разобранных строк выгрузки: заявки, бригада, сеть, проверка.

    Общая часть зоны заказчика и выгрузки, которую принёс диспетчер: день
    из файла `восток.csv`, загруженного кнопкой, обязан выйти тем же, что
    зона «восток», — иначе два пути к одним данным давали бы два плана.
    Откуда брать сеть, решает зовущий (`сеть` — функция от точек): зоны
    строят её под свои адреса и кладут в репозиторий, выгрузка берёт
    готовую или строит в каталоге состояния.
    """
    office_point = geo.get(office_text) or {}
    if not office_point.get("lat"):
        raise ValueError(f"офис «{office_text}» не геокодирован — "
                         f"инженерам неоткуда выезжать")

    orders, skipped = build_orders(rows, geo)
    if skipped and not quiet:
        print(f"  пропущено заявок: {len(skipped)}")
        for s in skipped[:5]:
            print(f"    {s['id']}: {s['почему']} — {s['address']}")

    engineers = build_engineers(n_engineers, {
        "lat": office_point["lat"], "lon": office_point["lon"],
        "address": office_text,
    }, orders=orders)

    # Сеть: все точки заявок, офис и дома выездных инженеров. Последние
    # обязательны: без своей точки в сети «дом» выездного приклеится к
    # ближайшему узлу, а ближайший — это его же первая заявка, и весь
    # смысл базирования пропадёт.
    points = [{"lat": o.lat, "lon": o.lon, "district": o.district}
              for o in orders]
    points.append({"lat": office_point["lat"], "lon": office_point["lon"],
                   "district": "офис"})
    for e in engineers:
        if (e.home_lat, e.home_lon) != (office_point["lat"], office_point["lon"]):
            points.append({"lat": e.home_lat, "lon": e.home_lon,
                           "district": "выездная точка"})
    net = сеть(points)

    for o in orders:
        o.node = net.nearest_node(o.lat, o.lon)
    office_node = net.nearest_node(office_point["lat"], office_point["lon"])
    for e in engineers:
        # Узел ищется по собственным координатам инженера: у городских
        # это офис, у выездных — их город. Раньше здесь всем без разбора
        # присваивался офисный узел, и базирование не имело бы смысла.
        e.home_node = net.nearest_node(e.home_lat, e.home_lon)

    day = Day(date=date, orders=orders, engineers=engineers, network=net,
              hard_end=HARD_END, ident=ident)

    # Проверка дня писалась ровно под этот момент: «генератор заменится на
    # загрузчик, и молчаливо неверный `Day` не упадёт — он спланируется и
    # даст покрытие 30% и полдня разбирательств». Но подключена она была
    # только к `selfcheck` и `scalebench`, то есть к синтетике, а на пути
    # настоящих данных не звалась ни разу. Стоит она 0 мс.
    #
    # Поломка — это отказ: день, которым планировщик подавится, лучше не
    # отдавать вовсе, чем отдать вместе с объяснением, почему алгоритм
    # «вдруг стал хуже». Предупреждения печатаются, потому что они про
    # странность, а не про непригодность.
    from .validate_day import check as _проверить_день
    поломки, предупреждения = _проверить_день(day)
    if поломки:
        raise ValueError(
            f"день «{ident}» не годен к планированию:\n  "
            + "\n  ".join(поломки))
    if предупреждения and not quiet:
        for строка in предупреждения:
            print(f"  ! {строка}")

    return day


