"""
Доверительный интервал для замеров — по t, а не по 1,96.

Замеры пересчёта идут по шести дням (три участка по два зерна солвера), и
1,96 там занижает половину интервала в 2,571 / 1,96 ≈ 1,31 раза: при пяти
степенях свободы нормальная аппроксимация не годится. Правило проекта —
интервал по всем источникам случайности и по t; здесь это одна функция на
все замеры, чтобы 1,96 не возвращалось по одному файлу.
"""

from __future__ import annotations

import statistics

from scipy.stats import t as _t


def ci95(values: list[float]) -> tuple[float, float]:
    """Среднее и половина 95% интервала по t с n − 1 степенями свободы.

    Значения — парные разности по независимым единицам (дням), а не по
    прогонам внутри дня: прогоны одного дня делят план и зерно солвера.
    """
    if not values:
        return 0.0, 0.0
    m = statistics.mean(values)
    if len(values) < 2:
        return m, 0.0
    n = len(values)
    return m, float(_t.ppf(0.975, n - 1)) * statistics.stdev(values) / n ** 0.5
