/** Навык аварий — по справочнику ТЗ (`dictionary.ts`); им же движок
    помечает аварии, которые приносит пересчёт. */
export const URGENT_SKILL = 'emergency';

/** С какой минуты аварию есть кому взять: самое раннее начало смены у тех,
    кто умеет аварии. `null` — таких в бригаде нет.

    Авария ждёт исполнителя недолго (у движка — три часа от прихода), а смены
    аварийщиков в нашей модели бригады начинаются поздно: во всех трёх зонах
    в 10:00. Авария в 07:00 давала «0 из 2» — движок прав, но диспетчер видел
    провал без причины. Поэтому время аварии по умолчанию — не раньше этой
    минуты, а раньше неё интерфейс говорит словами, почему может не
    встать (решение владельца 22 сентября). */
export function urgentFrom(engineers: Iterable<{ skills: string[]; shift_start: number }>): number | null {
  let first: number | null = null;
  for (const engineer of engineers) {
    if (!engineer.skills.includes(URGENT_SKILL)) continue;
    if (first === null || engineer.shift_start < first) first = engineer.shift_start;
  }
  return first;
}
