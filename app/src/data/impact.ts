export interface Impact {
  /** Во что событие обходится дню, если ничего не делать. */
  cost: string;
  /** Что возвращает пересчёт. */
  back: string;
  /** Стоит ли жать. Замерено, а не придумано. */
  verdict: 'press' | 'skip';
  verdictText: string;
  /** Чем измерено число выше — сколько дней и прогонов, какой интервал.
      Не у каждого события: у отмены цифр нет вовсе, там утверждение
      логическое («работы стало меньше»), а не статистическое, и
      «как посчитано» ему предъявить нечего. `null` явно, а не пропуск
      поля — чтобы не забыть добавить, когда замер появится. */
  basis: string | null;
}

