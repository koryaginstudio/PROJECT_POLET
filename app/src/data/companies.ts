/** Название компании по номеру точки обслуживания.

    Раздаётся по сквозному номеру адреса (`C0001`, `C0002`…), а не по месту в
    списке: номер закреплён за адресом навсегда, и компания на нём не съедет
    от смены сортировки или отбора.

    Одной компании достаётся несколько адресов — так и бывает: у сети
    магазинов точки по всему городу, и заявки с них приходят в один и тот же
    договор. Раздача по остатку даёт каждой поровну, и в базе видно обе
    стороны — и «сколько адресов у этого клиента», и «сколько заявок с
    каждого». */
/** Сеть, которой принадлежит точка: имя без номера филиала. По нему считают,
    сколько в базе компаний, — точек больше, чем сетей. */
export function chainOf(number: number): string {
  if (!Number.isFinite(number) || number <= 0) return COMPANIES[0];
  return COMPANIES[(number - 1) % COMPANIES.length];
}

/** Имя точки в базе: сеть, а у второй и следующих её точек — номер филиала.

    Названий шестьдесят пять, а номера точек идут подряд по всей истории и
    давно перевалили за четыреста: без номера филиала точки, чьи номера
    отличаются на кратное длине списка, получали одно имя, и в базе это
    читалось как две записи об одном клиенте — C0002 и C0392 обе звались
    «ТД „Северный ветер"».

    Номер филиала — это круг, на котором список исчерпался: он считается из
    номера самой точки, поэтому имя закреплено за ней навсегда и не зависит от
    того, какие точки пришли рядом. */
export function companyOf(number: number): string {
  const chain = chainOf(number);
  if (!Number.isFinite(number) || number <= 0) return chain;
  const round = Math.floor((number - 1) / COMPANIES.length);
  return round === 0 ? chain : `${chain} №${round + 1}`;
}

