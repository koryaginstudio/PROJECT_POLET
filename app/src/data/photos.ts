/* Фотографии инженеров.

   Своих карточек сотрудников у стенда нет: инженеры приходят из планов
   движка, а в плане есть имя, навыки и смена — фотографии там нет и не будет.
   Поэтому снимки раздаются стендом: список лежит здесь, привязка считается по
   табельному номеру.

   Привязка постоянная, а не случайная при каждом открытии: человек с одним и
   тем же лицом на карточке узнаётся с одного взгляда, а лицо, меняющееся при
   перезагрузке, — хуже, чем его отсутствие. Поэтому «случайность» здесь
   только в том, что порядок снимков не совпадает с порядком инженеров, — сам
   расклад считается из табельного и не меняется.

   Когда придут настоящие фотографии, отсюда уйдёт только источник: карточка
   спрашивает снимок по инженеру и не знает, откуда он взялся. */

const PHOTOS = [
  'photo-02.jpg',
  'photo-03.jpg',
  'photo-04.jpg',
  'photo-05.jpg',
  'photo-06.jpg',
  'photo-07.jpg',
  'photo-08.jpg',
  'photo-09.jpg',
  'photo-10.jpg',
  'photo-11.jpg',
  'photo-12.jpg',
  'photo-13.jpg',
  'photo-p1.jpg',
  'photo-p2.jpg'
];

/* Простая свёртка табельного в число. Криптографии здесь не нужно — нужно,
   чтобы порядок снимков не повторял порядок табельных: иначе раздача читалась
   бы как список, а не как раздача. */
function hash(id: string): number {
  let value = 0;
  for (let index = 0; index < id.length; index += 1) {
    value = (value * 31 + id.charCodeAt(index)) >>> 0;
  }
  return value;
}

/* Закреплённые снимки: этим людям лицо выбрано вручную, и раздача их не
   трогает. Всё остальное разбирается из общей очереди. */
const PINNED: Record<string, string> = {
  E00: 'photo-p1.jpg', // Соколов
  E11: 'photo-p2.jpg' // Виноградов
};

/** Снимки для списка инженеров: табельный → путь от корня сайта.

    Раздаём всем сразу, а не каждому по отдельности: снимок, посчитанный из
    одного табельного, рано или поздно совпадает с чужим — два инженера с
    одним лицом в соседних карточках выглядят сбоем данных. Здесь очередь
    перемешивается свёрткой табельного, а снимки разбираются по одному, и
    повтор появляется только когда людей больше, чем фотографий. */
export function photosFor(ids: string[]): Map<string, string> {
  const map = new Map<string, string>();
  const queue: string[] = [];
  for (const id of [...ids].sort((a, b) => hash(a) - hash(b) || a.localeCompare(b))) {
    if (PINNED[id]) map.set(id, `/photos/${PINNED[id]}`);
    else queue.push(id);
  }

  /* Из общей очереди убраны закреплённые снимки: иначе лицо, отданное
     вручную, встретилось бы в списке второй раз. */
  const taken = new Set(Object.values(PINNED));
  const free = PHOTOS.filter((name) => !taken.has(name));
  queue.forEach((id, index) => {
    map.set(id, `/photos/${free[index % free.length]}`);
  });
  return map;
}
