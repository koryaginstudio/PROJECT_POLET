/* Цвета для знаков. Приглушённые: знак стоит там же, где фотография, и не
   должен спорить с ней яркостью в одном ряду. */
const MARK_COLORS = [
  '#5B6B7C',
  '#6E6A82',
  '#4F7268',
  '#7C6350',
  '#5A6E86',
  '#7A5F6B',
  '#57705A',
  '#6B6450'
];

function hash(text: string): number {
  let value = 0;
  for (let index = 0; index < text.length; index += 1) {
    value = (value * 31 + text.charCodeAt(index)) >>> 0;
  }
  return value;
}

/** Инициалы: первая буква фамилии и первая буква имени. Выгрузка называет
    бригаду то одной фамилией, то ФИО целиком — берём то, что пришло. */
function initialsOf(name: string): string {
  const parts = name.trim().split(/\s+/).filter(Boolean);
  if (parts.length === 0) return '—';
  return parts
    .slice(0, 2)
    .map((part) => part[0].toUpperCase())
    .join('');
}

/* Знак рисуется здесь же и отдаётся картинкой. Так вызывающей стороне не
   нужно знать, лицо ей досталось или знак: и то и другое — `src` для `img`,
   и ни одна карточка от этого не меняется. */
function markFor(id: string, name: string): string {
  const color = MARK_COLORS[hash(id) % MARK_COLORS.length];
  const svg =
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 200 200">` +
    `<rect width="200" height="200" fill="${color}"/>` +
    `<text x="100" y="100" fill="#fff" font-family="Onest, system-ui, sans-serif" ` +
    `font-size="78" font-weight="600" text-anchor="middle" dominant-baseline="central">` +
    `${initialsOf(name)}</text></svg>`;
  return `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`;
}

export interface Faced {
  id: string;
  name: string;
}

/** Человек, а не запись. Табельный номер для этого не годится: у каждого
    участка своя нумерация с нуля, и «E05» из Востока — другой человек, чем
    «E05» из Юго-востока. По номеру снимки и повторялись трижды — по разу на
    участок.

    Имя же у человека одно во всех разделах: и в плане движка, и в
    справочнике оно приходит из той же выгрузки. Нормализуем написание —
    регистр, двойные пробелы, «ё» — и получаем ключ. */
const whoOf = (name: string) =>
  name.trim().toLowerCase().replace(/ё/g, 'е').replace(/\s+/g, ' ');

/* Кому какой снимок достался — двумя указателями.

   По записи справочника: её ключ — «участок:номер», и запись эта у каждого
   человека своя. Именно по ней раздача и идёт: в базе лежит штат всех трёх
   участков разом, и одинаковое лицо в двух строках подряд читается как сбой
   данных, кем бы эти двое ни были.

   По имени: в плане расчёта у инженера нет участка в номере, там он просто
   «E05». Оттуда лицо и спрашивают карточки диспетчерской. Имя — то же, что
   в справочнике, и по нему человек находится. */
const byRecord = new Map<string, string>();
const byName = new Map<string, string>();
/* Все записи справочника — и те, кому снимка не хватило. По этому списку
   видно, кого мы уже знаем: запись из справочника без снимка получает знак,
   а не чужое лицо. Прежде она брала лицо тёзки, и в конце списка снова шли
   повторы — восемь штук, ровно на разницу между штатом и числом снимков. */
const known = new Set<string>();

/** Раздать снимки всему штату разом.

    Раздача идёт по ключам записей, отсортированным по алфавиту: у одного и
    того же справочника она всегда одна и та же, от запуска к запуску и от
    раздела к разделу. Снимков тридцать четыре; кому не хватило — знак с
    инициалами.

    Зовётся, когда собран справочник: там штат целиком, включая тех, кого
    нет в открытом расчёте. */
export function noteCrew(crew: Faced[]): void {
  byRecord.clear();
  byName.clear();
  known.clear();
  const rows = [...crew].sort((a, b) => a.id.localeCompare(b.id));
  rows.forEach((one, index) => {
    known.add(one.id);
    if (index >= PHOTOS.length) return;
    const face = `/photos/${PHOTOS[index]}`;
    byRecord.set(one.id, face);
    /* Имя запоминаем за первой же записью: в плане участка нет, и выбрать
       из трёх одинаковых имён там не из чего — пусть будет первое по
       порядку, лишь бы всегда одно и то же. */
    const who = whoOf(one.name);
    if (who && !byName.has(who)) byName.set(who, face);
  });
}

/** Лицо одного инженера: снимок, закреплённый за его записью, или знак с
    инициалами. */
export function faceOf(engineer: Faced): string {
  const own = byRecord.get(engineer.id);
  if (own) return own;
  /* На общей карте нескольких участков номер составной: «расчёт::инженер».
     Отрезаем чужую половину — дальше поиск идёт как обычно. */
  const cut = engineer.id.indexOf('::');
  if (cut > 0) {
    const short = byRecord.get(engineer.id.slice(cut + 2));
    if (short) return short;
  }
  /* Запись из справочника без снимка — знак. Лицо тёзки ей не годится:
     рядом в списке стоял бы тот же человек с тем же лицом. */
  if (known.has(engineer.id)) return markFor(engineer.id, engineer.name);
  const who = whoOf(engineer.name);
  const named = byName.get(who);
  if (named) return named;
  /* Штат ещё не роздан — держимся имени: до загрузки справочника лицо хотя
     бы не скачет от карточки к карточке. */
  if (byRecord.size === 0 && who) return `/photos/${PHOTOS[hash(who) % PHOTOS.length]}`;
  return markFor(engineer.id, engineer.name);
}

/** Лица для списка: табельный → путь или знак. */
export function photosFor(crew: Faced[]): Map<string, string> {
  return new Map(crew.map((engineer) => [engineer.id, faceOf(engineer)]));
}
