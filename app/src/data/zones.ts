/* Цвет участка.

   Участок красится и на карте — подложкой под маршрутами, — и в плашке
   смены, точкой у своего названия. Цвет там и там обязан быть один: он и
   есть связь между пятном на городе и строкой в перечне.

   Считается он от названия, а не от места участка в списке. По списку
   выходило бы «Восток — первый цвет», и стоило снять один участок с карты,
   как оставшиеся перекрашивались: тот же район, а пятно другого цвета.
   Название не меняется — не меняется и цвет.

   Одного хеша мало: «Юго-восток» и «Югоцентр» честно попадали в один и тот
   же оттенок, а два одинаковых пятна на соседних районах — хуже случайного
   цвета. Поэтому палитра раздаётся сразу на весь набор участков: каждый
   просит свой цвет по хешу, занятый — берёт следующий свободный. Набор
   один и тот же у карты и у плашки, и порядок в нём не важен: раздача идёт
   по названиям, отсортированным по алфавиту.

   Оттенки приглушённые и разведены по кругу: подложка работает почти
   прозрачной, и участок узнают по пятну под маршрутами, а не по яркости
   самого пятна. */

export const ZONE_COLORS = ['#4C7DF0', '#3FAE8C', '#E0864A', '#A46BD8', '#C9556F', '#4FA3C7'];

/** Устойчивое число по строке. Обычный полиномиальный свёртыш: важно не
    качество рассыпания, а повторяемость от запуска к запуску. */
const hash = (text: string): number => {
  let sum = 0;
  for (let i = 0; i < text.length; i += 1) sum = (sum * 31 + text.charCodeAt(i)) >>> 0;
  return sum;
};

/** Цвета для набора участков: «Восток» → «#A46BD8» и так далее. */
export function zonePalette(titles: string[]): Map<string, string> {
  const out = new Map<string, string>();
  const taken = new Set<number>();
  for (const title of [...new Set(titles)].sort((a, b) => a.localeCompare(b))) {
    let slot = hash(title) % ZONE_COLORS.length;
    for (let step = 0; taken.size < ZONE_COLORS.length && taken.has(slot); step += 1) {
      slot = (slot + 1) % ZONE_COLORS.length;
    }
    taken.add(slot);
    out.set(title, ZONE_COLORS[slot]);
  }
  return out;
}
