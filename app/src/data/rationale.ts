/* Откуда взялось то, чего в выгрузке не было.

   Часть полей набора выгрузка не содержит вовсе, и они достроены при сборке.
   Достроены не наугад — у каждого своё основание, — но человеку, который
   видит в карточке «Автомобиль», основание ниоткуда не видно, и поле читается
   как факт из учётной системы. Это хуже, чем допущение, названное вслух: на
   защите такой вопрос задают первым.

   Поэтому рядом с каждым достроенным полем стоит значок, а объяснение лежит
   здесь. Текст один на весь интерфейс: карточка, таблица и панель обязаны
   объяснять одно и то же одними словами.

   Когда транспорт начнёт приходить из учётной системы, эти объяснения уйдут
   вместе с допущением — а до тех пор они честнее молчания. */

import { transportName } from './dictionary.ts';

/* Объяснение к типу транспорта. Одно на тип: у всех автомобилистов оно
   обязано быть одним и тем же — это свойство транспорта, а не человека.

   Три коротких утверждения, и больше ничего: зачем этот транспорт, что он
   даёт по заявкам и откуда взялся. Длинное объяснение под значком не читают
   вовсе. */

const TRANSPORT_WHY: Record<string, string> = {
  car:
    'Автомобиль — чтобы возить груз: катушку кабеля, стремянку, сварочный аппарат. ' +
    'Берёт любые заявки, включая те, где автомобиль требуется: аварии, работа с кабелем, ' +
    'подключения.',
  walk:
    'Пешком — работа без груза в шаговой доступности от офиса. ' +
    'Заявки, где требуется автомобиль, ему не достанутся.',
  bike:
    'Велосипед — работа без груза в пределах района, быстрее пешего. ' +
    'Заявки, где требуется автомобиль, ему не достанутся.',
  transit:
    'Общественный транспорт — работа без груза с разъездами по городу. ' +
    'Заявки, где требуется автомобиль, ему не достанутся.'
};

const TRANSPORT_SOURCE = 'В выгрузке типа транспорта нет — он проставлен при сборке набора.';

/** Почему у инженера именно этот транспорт. */
export function transportWhy(transport: string | null | undefined): string | null {
  if (!transport) return null;
  const why = TRANSPORT_WHY[transport];
  if (!why) return `${transportName(transport)}. ${TRANSPORT_SOURCE}`;
  return `${why} ${TRANSPORT_SOURCE}`;
}

/* Вид работ, из которого выведено требование к транспорту. Список тот же, что
   в сборке набора: правка в одном месте требует правки в другом. */
const CARGO_WORK: Record<string, string> = {
  Авария: 'инструмент и запас кабеля на аварийный выезд',
  'Работа с кабелем': 'катушку кабеля, стремянку, сварочный аппарат',
  'Заявка на подключение': 'роутер, кабель, стремянку',
  'Заказ подключения/Дозаказ оборудования': 'роутер и кабель'
};

/** Почему заявка требует транспорт — и почему у остальных требования нет. */
export function requiredTransportWhy(
  required: string | null | undefined,
  workType: string
): string | null {
  if (!required) return null;
  const cargo = CARGO_WORK[workType];
  return (
    (cargo ? `На объект надо везти: ${cargo}. ` : 'На объект надо везти оборудование. ') +
    'Заявку возьмёт только инженер с автомобилем. ' +
    'В выгрузке требования нет — оно выведено из вида работ.'
  );
}

