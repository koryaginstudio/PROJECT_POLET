export type KnobKind = 'number' | 'slider';

export interface Knob {
  /** Имя как в движке. По нему его ищет тот, кто читал код. */
  key: string;
  label: string;
  /** Что оно делает и чем оборачивается, если подвинуть. */
  what: string;
  kind: KnobKind;
  factory: number;
  min: number;
  max: number;
  step: number;
  unit?: string;
  /** Доезжает ли значение до расчёта. Ложь — поле показано, но то, что в
      нём набрано, расчёт не читает, и об этом сказано прямо на экране. */
  wired: boolean;
}

