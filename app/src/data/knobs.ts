/* Настройки движка: ровно семь.

   Число не округлённое и не выбранное на глаз — оно записано в
   договорённости со стороной движка и держится на двух доводах.

   Первый: у каждой из семи есть смысл на языке диспетчера. «На сколько
   завышать оценку времени работ» — вопрос, на который в компании есть
   ответ, потому что она знает, насколько её визиты затягиваются. «Сколько
   визитов за раз разбирает алгоритм на каждой итерации» — вопрос, на
   который ответа нет ни у кого, кроме того, кто ставил замеры.

   Второй: остальные переменные движка опасно выставлять наружу, и вред у
   каждой свой. Бюджет поиска — прямой самострел: поставил шестьдесят
   секунд, и интерфейс завис на минуту; поставил треть секунды, и планы
   стали хуже без единого сообщения об этом. Шум и размах выбивания тихо
   ухудшают план, и обратной связи об этом нет ниоткуда. Веса простоя и
   риска калиброваны совместно, и сдвиг одного без другого разбалансирует
   целевую функцию так, что с рабочего места это не диагностируется. Число
   прогонов симуляции на план не влияет вовсе — только на точность
   статистики в сводке.

   Здесь был перебор, и его стоит назвать. На экране лежали двадцать полей:
   к семи согласованным добавились одиннадцать внутренних и два кадровых.
   Пришли они из присланного списка всех переменных движка, половина
   которого была помечена как «в интерфейсе этого не будет», — и пометка не
   была услышана. Поле, которое молча ничего не делает, действительно хуже
   отсутствующего; но вывод из этого — убрать поле, а не дотянуть его до
   солвера.

   Кадровые — длина смены и допустимые часы начала — убраны не потому, что
   дорого сделать, а потому, что делать не надо. График выхода приходит
   готовым файлом. Поле, которым диспетчер переопределяет присланный
   кадровый график, создаёт два источника правды про вещь с трудовыми
   последствиями.

   Если внутренние всё же нужно крутить без пересборки — им место в конфиге
   сервера рядом с движком, а не на экране диспетчера.

   ── Что из семи доезжает до расчёта ──

   Флаг `wired` у каждой настройки говорит правду, а не обещание. Пять
   переменных солвера — множитель длительности, два зазора, вес
   равномерности и штраф за смену исполнителя — расчёт получает не отсюда,
   а из формы нового расчёта: она открывается значениями `engine.ts`, и они
   же записываются в историю вместе с планом. Значение, набранное в этом
   каталоге, до планировщика не доходит — каталог их только показывает.
   Пока два хранилища не сведены в одно, у этих пяти стоит `wired: false`,
   и экран настроек говорит «два из семи», а не «все семь».

   Два порога риска — единственное, что расчёт читает прямо отсюда: ими
   планировщик подписывает запас у каждого визита. Со стороны движка это
   тоже так: пороги идут в экспорт плана, а не в солвер. */

