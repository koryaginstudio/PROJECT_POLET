export const KNOB_BY_KEY = new Map<string, Knob>(
  KNOBS.flatMap((group) => group.knobs.map((knob) => [knob.key, knob] as const))
);

/** Значения, с которых начинается чистая установка. */
export function factoryKnobs(): Record<string, number> {
  const out: Record<string, number> = {};
  for (const group of KNOBS) {
    for (const knob of group.knobs) out[knob.key] = knob.factory;
  }
  return out;
}

export const WIRED_COUNT = KNOBS.reduce(
  (sum, group) => sum + group.knobs.filter((knob) => knob.wired).length,
  0
);

export const TOTAL_COUNT = KNOBS.reduce((sum, group) => sum + group.knobs.length, 0);

/* ─── что из этого задано у нас ──────────────────────────────────────────

   Значения живут в браузере: сервера настроек у нас нет, и притворяться,
   что он есть, нельзя. */

const STORE = 'polet.knobs.v2';

type KnobValues = Record<string, number>;

function read(): KnobValues {
  const base = factoryKnobs();
  if (typeof localStorage === 'undefined') return base;
  try {
    const raw = localStorage.getItem(STORE);
    if (!raw) return base;
    const saved = JSON.parse(raw) as KnobValues;
    /* По одному ключу, а не целиком: в записи из прошлой версии могло
       остаться то, чего на экране больше нет, и подставлять это обратно
       незачем. */
    for (const key of Object.keys(base)) {
      if (typeof saved[key] === 'number' && Number.isFinite(saved[key])) base[key] = saved[key];
    }
    return base;
  } catch {
    return base;
  }
}

let values: KnobValues = read();

export const knobValues = (): KnobValues => ({ ...values });

export function setKnob(key: string, value: number): void {
  values = { ...values, [key]: value };
  try {
    localStorage.setItem(STORE, JSON.stringify(values));
  } catch {
    /* Хранилище закрыто настройками браузера — значение живёт до
       перезагрузки. Это хуже, чем ничего не делать, но не ошибка. */
  }
}

export function resetKnobs(): void {
  values = factoryKnobs();
  try {
    localStorage.removeItem(STORE);
  } catch {
    /* см. выше */
  }
}

/** Сколько значений уведено от заводских. */
export function changedKnobs(): number {
  const base = factoryKnobs();
  return Object.keys(base).filter((key) => values[key] !== base[key]).length;
}

/* ─── пороги риска для планировщика ──────────────────────────────────────

   Единственное, что расчёт читает из каталога напрямую. Запас у визита —
   минуты от планового начала до конца окна; ниже красного порога визит
   «под угрозой», ниже жёлтого — «впритык», выше — спокойный. */

export interface RiskThresholds {
  /** Запас меньше — визит под угрозой, мин. */
  high: number;
  /** Запас меньше — визит впритык, мин. */
  medium: number;
}

/** Пороги как они заданы сейчас. Жёлтый не ниже красного: иначе красный
    не наступил бы никогда, а каталог этого не запрещает — только предупреждает. */
export function riskThresholds(): RiskThresholds {
  const high = values.risk_high ?? KNOB_BY_KEY.get('risk_high')!.factory;
  const medium = values.risk_medium ?? KNOB_BY_KEY.get('risk_medium')!.factory;
  return { high, medium: Math.max(high, medium) };
}
