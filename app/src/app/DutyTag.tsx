import { Icon } from '../ds/components/core/Icon.jsx';

/* Пометка «в работе» — у расчёта, взятого на свой день, и у всего, что из
   него вышло.

   Кнопка «В работу» говорит, по какому из расчётов дня работают на самом
   деле: остальные прогоны того же дня — черновики к нему. Раньше это знала
   только сама кнопка, и в базах рабочий расчёт лежал вперемешку с
   черновиками. Пометка говорит то же самое в каждом виде базы — в списке, в
   таблице, в карточке и в разрезе по состоянию, — и выглядит везде
   одинаково: одна вещь, один знак. */
export function DutyTag({ what = 'расчёт' }: { what?: string }) {
  return (
    <span className="dutytag" title={`Этот ${what} взят в работу на свой день`}>
      <Icon name="check-circle" size={11} />
      В работе
    </span>
  );
}
