/* Почему пересчёт по событию сейчас недоступен — одной причиной, первой по
   порядку. Одна функция на окно правки и на экран «Воздействия»: прежде
   тексты жили в двух местах и расходились, а диспетчер должен читать одну и
   ту же причину, где бы он ни упёрся в серую кнопку.

   Причин три, и совет у каждой свой: включить программу, открыть расчёт
   дня, завести расчёт у программы. `null` — пересчитывать можно. */
export interface ReplanBlock {
  /** Что случилось — жирным. */
  what: string;
  /** Что делать. */
  todo: string;
}

export function replanBlocked(live: boolean, savedReplan: boolean, hasDay: boolean): ReplanBlock | null {
  if (!live) {
    return {
      what: 'Программа расчёта не запущена.',
      todo:
        'Пересчёт делает она. Как включить — в настройках, на вкладке «Данные». Пока можно ' +
        'пересобрать день другими правилами через «Ручное управление».'
    };
  }
  if (savedReplan) {
    return {
      what: 'Это сохранённый пересчёт.',
      todo: 'Пересчитывать можно от расчёта дня — откройте его.'
    };
  }
  if (!hasDay) {
    return {
      what: 'Этот расчёт посчитан в браузере.',
      todo:
        'Дня у программы расчёта за ним нет — пересобирать нечего. Откройте или заведите ' +
        'расчёт у программы расчёта.'
    };
  }
  return null;
}
