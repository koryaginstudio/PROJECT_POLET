/* Выделение общее на весь экран: клик в любой панели меняет правую панель. */
export type Selection =
  | { kind: 'overview' }
  | { kind: 'engineer'; id: string }
  | { kind: 'order'; id: string }
  /** Раскрытая группа: список заявок или инженеров по классификации. */
  | { kind: 'group'; id: string }
  /* Готовый список — снимок набора на момент щелчка.

     Отличие от группы принципиальное: группа знает только своё имя и
     пересобирается из данных каждый раз, поэтому её содержимое ехало вместе
     с ползунком времени. Список несёт сами номера, поэтому правая панель
     показывает ровно то, по чему щёлкнули, и ползунок его не трогает. */
  | {
      kind: 'list';
      of: 'orders' | 'engineers';
      title: string;
      eyebrow: string;
      note: string;
      ids: string[];
    };

export const OVERVIEW: Selection = { kind: 'overview' };
