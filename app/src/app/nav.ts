/** Разделы баз данных: они живут над прогоном, поэтому у них своя загрузка,
    выбор прогона к ним не применяется и правая панель им не нужна. */
export const DB_SECTIONS = new Set<SectionId>([
  'db-runs',
  'db-orders',
  'db-services',
  'db-clients',
  'db-routes',
  'db-engineers'
]);

export const isDbSection = (id: SectionId) => DB_SECTIONS.has(id);

/** Прогон выбирают там, где он определяет содержимое экрана целиком —
    в диспетчерской (какой план строим) и в мониторинге (за исполнением
    какого плана следим). Сравнение и статистика смотрят на все прогоны
    сразу, поэтому переключателя у них нет: он бы обещал влияние, которого
    нет. */
export const isRunScoped = (id: SectionId) =>
  id === 'dispatch' || id === 'monitor' || id === 'control';

/** Разделы, которые читают все прогоны сразу: им нужны справочники, а правая
    панель — нет. Статистика тоже стоит над прогоном, но справочники ей пока
    не нужны: наполнение снято под новую сборку. */
export const isCrossRun = (id: SectionId) => id === 'compare' || id === 'stats' || isDbSection(id);

