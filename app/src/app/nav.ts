/* Разделы системы.

   Первые три группы — этапы, из которых состоит любой транспортный процесс:
   сначала планируют, потом смотрят, что получается, потом вмешиваются. Так
   устроена работа в отрасли, и так же названы группы — диспетчер ищет раздел
   по стадии своей работы, а не по тому, как у нас назван экран.

   **Планирование** — «что должно получиться». Дашборд отвечает на вопрос
   «как дела в целом» и служит входом, диспетчерская строит план движком.

   **Мониторинг и контроль** — «что происходит и что получилось». Мониторинг
   читает срез в реальном времени, по часам, а не по тому моменту, который
   подвинул диспетчер. Сравнение и статистика — тот же контроль, только
   поверх результатов: они смотрят назад, на посчитанное, а не ведут смену.

   **Управление** — «что с этим делать». Единственное место, где диспетчер
   не смотрит, а вмешивается: объявляет событие и видит, чего стоит на него
   среагировать.

   **Базы данных** стоят за этапами, отдельной группой. Раньше они жили в
   середине, внутри контроля, и группа выходила вдвое длиннее остальных: пять
   справочников, между ними тонкими чертами протиснуты мониторинг, сравнение
   и статистика. Формально это контроль, а на деле — другой вопрос: этапы
   отвечают «что с этой сменой», а базы — «что у нас есть вообще», по всем
   прогонам сразу и безотносительно того, какой день сейчас открыт. Разные
   вопросы должны стоять в разных группах, а не разделяться чертой внутри
   одной. Заодно этапы снова читаются подряд, не разорванные справочниками.

   Настройки движка вынесены вниз отдельно: это не раздел, куда ходят
   смотреть, а то, что меняют редко и осознанно. */

