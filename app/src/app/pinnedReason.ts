/* Причина, по которой закреплённая заявка не встала, — словами диспетчера.

   Движок пишет её так: «закреплена диспетчером за E00, и в его смене для неё
   не нашлось места» (или «…, но у него нет навыка», «…, а такого инженера в
   смене нет» — export.py, `_why_unassigned`). Табельный номер диспетчеру
   ничего не говорит, а подставить имя на его место нельзя: «за Артём Белов» —
   не по-русски, склонять фамилии в коде — ненадёжно. Поэтому имя выносится
   вперёд, в именительном: «Закрепил диспетчер: Артём Белов. В его смене для
   неё не нашлось места». Прочие причины возвращаются как есть. */

const PINNED = /^закреплена диспетчером за (\S+?),\s*(?:и |но |а )?(.+)$/;

const capital = (text: string) => text.charAt(0).toUpperCase() + text.slice(1);

/** Причина закреплённой заявки без табельного номера: «В его смене для неё
    не нашлось места». Не про закрепление — `null`. */
export function pinnedRest(text: string): string | null {
  const m = PINNED.exec(text.trim());
  return m ? capital(m[2]) : null;
}

export function pinnedReason(text: string, nameOf: (id: string) => string): string {
  const m = PINNED.exec(text.trim());
  if (!m) return capital(text);
  return `Закрепил диспетчер: ${nameOf(m[1])}. ${capital(m[2])}`;
}
