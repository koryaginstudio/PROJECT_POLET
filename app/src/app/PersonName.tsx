interface Props {
  name: string;
  /** Отчество отдельной строкой. В узком месте — в одну строку целиком. */
  stacked?: boolean;
}

/* Имя человека, разобранное на части.

   Фамилия — то, чем человека называют и ищут: в списке из тридцати четырёх
   глаз цепляется за неё, а не за имя. Поэтому она акцентная. Отчество, наоборот,
   в списке не нужно почти никогда — оно нужно, когда инженеру звонят, — и
   уходит второй строкой, где не мешает читать первую.

   Разбор держится того же правила, что и весь набор: показываем ровно то, что
   пришло. Одна фамилия — одна фамилия, фамилия с именем — без второй строки,
   полное ФИО — фамилия и имя сверху, отчество под ними. Набор, где отчеств нет
   вовсе, от этого не поедет. */
/* Отчество узнаём по окончанию: «Павлович», «Петровна». */
const PATRONYMIC = /(ович|евич|ьич|инич|овна|евна|ична|инична)$/i;

/* Фамилию — тоже по окончанию. Список не полон и полным быть не может, но
   покрывает то, что приходит: русские фамилии на -ов/-ев/-ин, польские и
   украинские на -ский/-ко, кавказские на -ян/-дзе/-швили. */
const SURNAME = /(ов|ев|ёв|ин|ын|ский|цкий|ской|цкой|ко|ук|юк|ян|дзе|швили|ых|их)(а)?$/i;

export function PersonName({ name, stacked = true }: Props) {
  const parts = name.trim().split(/\s+/).filter(Boolean);

  /* Порядок слов приходит разный, и выбирать из него нечего: в выгрузке
     заказчика человек записан «Фамилия Имя Отчество», а программа расчёта
     отдаёт «Имя Фамилия». Разбирать это по месту слова нельзя — половина
     имён тогда читается наоборот, и оранжевым горит имя вместо фамилии.

     Поэтому смотрим на сами слова. Отчество узнаётся по окончанию и всегда
     идёт последним; из двух оставшихся фамилия — та, что кончается как
     фамилия. Не опознали — оставляем как пришло: выдумывать порядок там,
     где его не видно, хуже, чем показать запись как есть. */
  let surname = parts[0];
  let first = parts[1];
  let patronymic = parts.slice(2).join(' ');

  if (parts.length === 2 && !SURNAME.test(parts[0]) && SURNAME.test(parts[1])) {
    surname = parts[1];
    first = parts[0];
    patronymic = '';
  } else if (parts.length === 3 && PATRONYMIC.test(parts[2]) && !SURNAME.test(parts[0])) {
    /* «Имя Фамилия Отчество» — редкость, но разбирается тем же правилом. */
    if (SURNAME.test(parts[1])) {
      surname = parts[1];
      first = parts[0];
      patronymic = parts[2];
    }
  }

  if (!surname) return null;

  return (
    <span className="pname">
      <span className="pname__line">
        <span className="pname__surname">{surname}</span>
        {first && <span className="pname__first"> {first}</span>}
        {patronymic && !stacked && <span className="pname__first"> {patronymic}</span>}
      </span>
      {patronymic && stacked && <span className="pname__patronymic">{patronymic}</span>}
    </span>
  );
}
