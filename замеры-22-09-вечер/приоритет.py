"""Приоритет распределения: во что обходится «Авария → Подключение → Ремонт».

Копия из `замеры-22-09-вечер/` для круга 22 сентября, вечер: восток пересчитан
после правки двух адресов (33527, 48227). Логика замера не менялась.

Три варианта первого уровня цели, парно по зёрнам на трёх участках:

    равные     (1, 1, 1)          — как было до 21 сентября: просто число
                                    несделанного;
    строгий    (1, 100, 10000)    — порядок организаторов целиком;
    аварии     (1, 1, 10000)      — строго только «авария максимальна»,
                                    подключение и ремонт равноценны.

Меряется назначенное (всего и по ступеням), выполненное по симуляции,
число исполнителей и километры. Разница к «равным» — парно по зёрнам, с
t-интервалом на 95%.

Запуск из корня:  python3 замеры-22-09-вечер/приоритет.py > замеры-22-09-вечер/приоритет.txt
"""

import math
import statistics
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from vrptw.core.load import load_day  # noqa: E402
from vrptw.core.simulate import monte_carlo  # noqa: E402
from vrptw.server import отпечаток_кода  # noqa: E402
from vrptw.settings import Settings  # noqa: E402
from vrptw.solvers import fast  # noqa: E402

ЗОНЫ = ("восток", "юго-восток", "югоцентр")
ЗЁРНА = range(6)
ШАГОВ = 500
ПРОГОНОВ = 200
ВАРИАНТЫ = {
    "равные": (1.0, 1.0, 1.0),
    "строгий": (1.0, 100.0, 10000.0),
    "аварии": (1.0, 1.0, 10000.0),
}
СТУПЕНЬ = {2: "аварии", 1: "подключения", 0: "ремонт/дозаказ"}
T95 = {5: 2.571}   # шесть пар — пять степеней свободы


def прогон(день, веса, зерно):
    p = Settings().params()
    p.lns_seconds = 0.0
    p.lns_iterations = ШАГОВ
    p.priority_weights = веса
    план = fast.solve(день, params=p, seed=зерно)
    проблемы = план.check_invariants(день)
    assert not проблемы, проблемы[:2]
    по_ступеням = {k: 0 for k in СТУПЕНЬ}
    for o in план.unassigned:
        по_ступеням[o.priority] += 1
    м = план.metrics(день)
    выполнено = monte_carlo(день, план, runs=ПРОГОНОВ, seed=зерно).done_mean
    return {
        "назначено": план.assigned_count,
        "выполнено": выполнено,
        "инженеров": м["engineers_used"],
        "км": м["km_total"],
        **{f"лежит:{СТУПЕНЬ[k]}": v for k, v in по_ступеням.items()},
    }


def интервал(разности):
    n = len(разности)
    среднее = statistics.fmean(разности)
    if n < 2 or all(d == разности[0] for d in разности):
        return среднее, 0.0
    return среднее, T95[n - 1] * statistics.stdev(разности) / math.sqrt(n)


def main():
    коммит = subprocess.run(["git", "rev-parse", "--short", "HEAD"],
                            capture_output=True, text=True).stdout.strip()
    print("Приоритет распределения: «Авария → Подключение → Ремонт / Дозаказ»")
    print(f"код {отпечаток_кода()} поверх {коммит}, боевые настройки, "
          f"{ШАГОВ} шагов, {len(ЗЁРНА)} зёрен, симуляция {ПРОГОНОВ} прогонов")
    print()

    дни = {з: load_day(з, quiet=True) for з in ЗОНЫ}
    итог = {в: {з: [прогон(дни[з], веса, s) for s in ЗЁРНА] for з in ЗОНЫ}
            for в, веса in ВАРИАНТЫ.items()}
    поля = list(итог["равные"][ЗОНЫ[0]][0])

    # средние по вариантам, три участка вместе
    print("три участка вместе, среднее по зёрнам")
    print(f"{'вариант':<10}" + "".join(f"{п:>18}" for п in поля))
    for в in ВАРИАНТЫ:
        строка = []
        for j, п in enumerate(поля):
            vals = [sum(итог[в][з][i][п] for з in ЗОНЫ) for i in range(len(ЗЁРНА))]
            строка.append(f"{statistics.fmean(vals):>18.1f}")
        print(f"{в:<10}" + "".join(строка))
    print()

    print("разница к «равным», три участка вместе, парно по зёрнам, 95%")
    for в in ("строгий", "аварии"):
        части = []
        for п in поля:
            разности = [sum(итог[в][з][i][п] - итог["равные"][з][i][п] for з in ЗОНЫ)
                        for i in range(len(ЗЁРНА))]
            m, h = интервал(разности)
            ноль = " (ноль внутри)" if h and abs(m) <= h else ""
            части.append(f"{п} {m:+.1f} ± {h:.1f}{ноль}")
        print(f"  {в}:")
        for ч in части:
            print(f"      {ч}")
    print()

    print("по участкам, среднее по зёрнам: назначено / лежит аварий / "
          "лежит подключений / лежит ремонта")
    for з in ЗОНЫ:
        for в in ВАРИАНТЫ:
            r = итог[в][з]
            ср = lambda п: statistics.fmean(x[п] for x in r)  # noqa: E731
            print(f"  {з:<11} {в:<8} {ср('назначено'):6.1f}  "
                  f"{ср('лежит:аварии'):5.1f}  {ср('лежит:подключения'):5.1f}  "
                  f"{ср('лежит:ремонт/дозаказ'):5.1f}")


if __name__ == "__main__":
    main()
