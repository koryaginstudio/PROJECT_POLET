"""Сколько ещё людей нужно, чтобы закрыть остаток — по трём участкам.

Копия из `замеры-22-09-вечер/` для круга 22 сентября, вечер: восток пересчитан
после правки двух адресов (33527, 48227). Логика замера не менялась.

Запуск из корня:
    python3 замеры-22-09-вечер/сколько-людей.py > замеры-22-09-вечер/сколько-людей.txt
"""

import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from vrptw.core.load import load_day  # noqa: E402
from vrptw.server import отпечаток_кода  # noqa: E402
from vrptw.settings import Settings  # noqa: E402
from vrptw.staffing import ЗЁРНА, ШАГОВ, сколько_нужно  # noqa: E402

код = отпечаток_кода()
коммит = subprocess.run(["git", "rev-parse", "--short", "HEAD"],
                        capture_output=True, text=True).stdout.strip()
параметры = Settings().params()
print("Сколько ещё людей нужно, чтобы закрыть остаток дня")
print(f"код {код} поверх коммита {коммит}, боевые настройки, "
      f"{ШАГОВ} шагов, зёрна {list(ЗЁРНА)}, "
      f"веса приоритета {параметры.priority_weights}")
print()
print("Метод: к дню по одному добавляются слоты из профилей бригады")
print("(навыки, транспорт, часы — как у настоящих инженеров), из офиса")
print("участка; день пересчитывается солвером, пока остаток не закроется")
print("или добавление перестанет помогать. В голове — наибольшее число")
print("слотов среди прогонов, закрывших остаток.")
print()
итого = 0
for зона in ("восток", "юго-восток", "югоцентр"):
    r = сколько_нужно(load_day(зона, quiet=True), параметры)
    итого += r["needed"]
    print(f"── {зона} " + "─" * (50 - len(зона)))
    print(f"   {r['phrase']}")
    if r["reliability"]:
        print(f"   {r['reliability']}")
    for с in r["slots"]:
        print(f"   +{с['count']} × {с['skills_title']}; {с['transport_title']}; "
              f"{с['shift_start']//60:02d}:00–{с['shift_end']//60:02d}:00")
    print("   по зёрнам (нужно, осталось):",
          ", ".join(f"з{s['seed']}: +{s['needed']}/{s['left']}" for s in r["seeds"]))
    print()
print(f"ИТОГО по трём участкам: +{итого}")
print()
print("Чем эти числа НЕ являются. Это ответ на вопрос «сколько слотов")
print("открыть сверх нашей бригады», а бригада — наше допущение: в выгрузке")
print("инженеров нет. Другой состав бригады даст другой ответ. Слоты")
print("берутся из профилей той же бригады, поэтому ответ говорит «ещё столько")
print("таких же», а не «столько людей нужно вообще».")
